fun resolveAppColorScheme(
    appThemeMode: AppThemeMode,
    isDarkTheme: Boolean,
): ColorScheme {
    return when (appThemeMode) {
        AppThemeMode.SYSTEM -> if (isDarkTheme) SystemDarkScheme else SystemLightScheme
        AppThemeMode.PAPER -> if (isDarkTheme) PaperDarkScheme else PaperLightScheme
        AppThemeMode.MIDNIGHT -> if (isDarkTheme) MidnightDarkScheme else MidnightLightScheme
        AppThemeMode.SUNSET -> if (isDarkTheme) SunsetDarkScheme else SunsetLightScheme
    }
}
